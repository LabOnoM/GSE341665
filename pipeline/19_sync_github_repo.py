#!/usr/bin/env python3
"""
19_sync_github_repo.py — rebuild the public GitHub repository from this project.

WHY THIS EXISTS
---------------
The repository LabOnoM/smad4kotooth was previously kept in step by hand-copying files
into a working copy that lived in a session scratchpad. Two problems: the working copy
was not durable, and "which files belong in the repo" existed only in whoever's head was
running the copies. This script makes the mapping explicit and repeatable.

WHAT THE REPOSITORY IS FOR
--------------------------
Code, and the small tables needed to check the code's output. It is one of four
destinations, and they do not overlap:

    GitHub  — the analysis code, live and versioned                    (this script)
    GEO     — sequence files + count/TPM matrices + metadata           (12, 13)
    Zenodo  — de-novo assembly, pipeline objects, exploratory arms     (18)
    Journal — manuscript, cover letter, figures, supplementary         (10, 15)

Large primary data are NEVER copied here: the data/ and reference/ folders carry only a
FILELIST.md naming what belongs there and where to get it.

USAGE
-----
    python3 scripts/JDR_reanalysis/19_sync_github_repo.py            # sync, report diff
    python3 scripts/JDR_reanalysis/19_sync_github_repo.py --push     # sync, commit, push

The working copy lives at  Submission_02_JMM_2026-07/1_GitHub/repo/  — i.e. inside the
submission folder where you would expect to find it, and gitignored so the outer project
never tries to track a nested repository. Override with --workdir.
"""

from __future__ import annotations

import argparse
import filecmp
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PIPE = os.path.join(ROOT, "scripts", "JDR_reanalysis")
V2 = os.path.join(ROOT, "00.Manuscript", "Submission_02_JMM_2026-07")
JOURNAL = os.path.join(V2, "4_Journal_JMM")
SUP = os.path.join(JOURNAL, "Supplementary")
FIGS = os.path.join(PIPE, "figures")
REMOTE = "https://github.com/LabOnoM/smad4kotooth.git"
DEFAULT_WORKDIR = os.path.join(V2, "1_GitHub", "repo")

# repo-relative destination  <-  source
FIGURE_FILES = ["Figure4_transcriptome.png", "Figure5_identity_switch.png",
                "Figure6_metabolic_convergence.png", "FigureS3_scref_umap_dotplot.png",
                "FigureS4A_pipeline.png", "FigureS4B_reanalysis.png"]
DATA_FILES = ["AI_panel_PanelApp_v4.37.csv", "AI_enrichment_sensitivity.csv"]


def run(cmd, cwd, check=True):
    return subprocess.run(cmd, cwd=cwd, check=check, capture_output=True, text=True)


def sync(workdir: str) -> list[str]:
    """Copy project files into the working copy. Returns the list of changed paths."""
    changed = []

    def put(src: str, rel: str) -> None:
        dst = os.path.join(workdir, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if not os.path.exists(dst) or not filecmp.cmp(src, dst, shallow=False):
            shutil.copy2(src, dst)
            changed.append(rel)

    # ---- pipeline code ----
    for f in sorted(os.listdir(PIPE)):
        if f.endswith((".py", ".R", ".sh")):
            put(os.path.join(PIPE, f), f"pipeline/{f}")

    # ---- the supplementary methods travel with the code ----
    sm = os.path.join(SUP, "Supplementary_Methods_Pipeline.md")
    if os.path.exists(sm):
        put(sm, "pipeline/SUPPLEMENTARY_METHODS.md")

    # ---- figures (outputs, small; the PDFs stay out of the repo) ----
    for f in FIGURE_FILES:
        p = os.path.join(FIGS, f)
        if os.path.exists(p):
            put(p, f"results/figures/{f}")

    # ---- small processed tables ----
    if os.path.isdir(SUP):
        for f in sorted(os.listdir(SUP)):
            if f.startswith("Supplementary_Data_") and f.endswith(".csv"):
                put(os.path.join(SUP, f), f"results/supplementary_data/{f}")
    for f in DATA_FILES:
        p = os.path.join(PIPE, "output", f)
        if os.path.exists(p):
            put(p, f"results/supplementary_data/{f}")

    # ---- provenance tables, generated so they cannot drift from the module ----
    sys.path.insert(0, PIPE)
    import ai_gene_provenance as prov  # noqa: E402
    txt = ("# Amelogenesis-imperfecta gene panel — verified provenance\n\n"
           "Generated by `pipeline/ai_gene_provenance.py`. Supplementary Tables S1–S2 of the\n"
           "manuscript. Every identifier verified against NCBI (`mim2gene_medgen` for MIM\n"
           "class, E-utilities for PMIDs).\n\n"
           "## Table S1 — audit of the retired hand-curated list\n\n"
           + prov.summary().split("PANEL")[0].strip() + "\n\n" + prov.audit_markdown()
           + "\n## Table S2 — verified provenance of the 31 PanelApp GREEN genes\n\n"
           + prov.panel_markdown() + "\n" + prov.panel_footnote())
    dst = os.path.join(workdir, "results", "supplementary_data",
                       "AI_gene_provenance_TableS1_S2.md")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    old = open(dst).read() if os.path.exists(dst) else None
    if old != txt:
        open(dst, "w").write(txt)
        changed.append("results/supplementary_data/AI_gene_provenance_TableS1_S2.md")
    return changed


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--workdir", default=DEFAULT_WORKDIR)
    ap.add_argument("--push", action="store_true", help="commit and push after syncing")
    ap.add_argument("-m", "--message", default="Sync pipeline and results from the project")
    args = ap.parse_args()

    wd = args.workdir
    if not os.path.isdir(os.path.join(wd, ".git")):
        os.makedirs(os.path.dirname(wd), exist_ok=True)
        print(f"cloning {REMOTE} -> {os.path.relpath(wd, ROOT)}")
        subprocess.run(["git", "clone", REMOTE, wd], check=True)
    else:
        run(["git", "fetch", "--quiet", "origin"], wd, check=False)

    changed = sync(wd)
    print(f"synced into {os.path.relpath(wd, ROOT)}")
    if not changed:
        print("  no changes — repository already matches the project")
    else:
        print(f"  {len(changed)} file(s) updated:")
        for c in changed[:20]:
            print(f"    {c}")
        if len(changed) > 20:
            print(f"    … and {len(changed)-20} more")

    status = run(["git", "status", "--porcelain"], wd).stdout.strip()
    if not status:
        print("  working tree clean; nothing to commit")
        return
    if not args.push:
        print("\n  (not committed — re-run with --push to commit and push)")
        return
    run(["git", "add", "-A"], wd)
    run(["git", "commit", "-m", args.message], wd)
    run(["git", "push", "origin", "HEAD"], wd)
    head = run(["git", "log", "--oneline", "-1"], wd).stdout.strip()
    print(f"  pushed: {head}")


if __name__ == "__main__":
    main()
